@dataclass(frozen=True)
class Tree:
    """A selftest tree: its files, and the findings it must report by line and by needle."""

    name: str
    pages: dict[str, str]
    lines: frozenset[tuple[str, int, Rule]]
    needles: tuple[tuple[str, str, Rule], ...]


SELFTEST_TREES = (
    Tree("clean", SELFTEST_PAGES | SELFTEST_LAYOUT, SELFTEST_EXTRA, ()),
    Tree("broken", SELFTEST_BROKEN, frozenset(), SELFTEST_NEEDLES),
    Tree("empty", {"LICENSE": "MIT\n"}, SELFTEST_EMPTY_FINDINGS, ()),
)


def needle_line(pages: dict[str, str], path: str, needle: str) -> int:
    """The first line of a page that holds the needle."""
    for number, line in enumerate(pages[path].split("\n"), 1):
        if needle in line:
            return number
    raise UsageError(f"selftest: no {needle!r} in {path}")


def expected(tree: Tree) -> frozenset[tuple[str, int, Rule]]:
    """Every (path, line, rule) a selftest tree must report, and nothing else."""
    found = set(tree.lines)

    # 1. A page named for a rule (docs/links.md ...) breaks it on each of its lines.
    for path, text in tree.pages.items():
        stem = posixpath.splitext(posixpath.basename(path))[0]
        rule = next((rule for rule in Rule if rule.value == stem), None)
        if rule is None:
            continue
        for number, line in enumerate(text.split("\n"), 1):
            if line.strip():
                found.add((path, number, rule))

    # 2. The needles, and each anatomy page the tree lacks.
    for path, needle, rule in tree.needles:
        found.add((path, needle_line(tree.pages, path, needle), rule))
    for path in ANATOMY_PAGES | LIGHT_PAGES:
        if path not in tree.pages:
            found |= {(path, 1, Rule.GUIDE_OPENING), (path, 1, Rule.GUIDE_NEXT)}
    return frozenset(found)


def build_tree(root: Path, pages: dict[str, str], env: dict[str, str]) -> None:
    """Writes a selftest tree into an empty git repository at `root`."""
    root.mkdir(parents=True)
    for path, text in pages.items():
        file = root / path
        file.parent.mkdir(parents=True, exist_ok=True)
        file.write_text(text, encoding="utf-8")
    try:
        subprocess.run(GIT_INIT, cwd=root, env=env, capture_output=True, check=True)
    except (FileNotFoundError, subprocess.CalledProcessError) as error:
        raise UsageError(f"git init failed: {error}") from error


def prove(tree: Tree, base: Path) -> tuple[list[str], int]:
    """The problems of one selftest tree, and how many findings it planted."""
    env = bare_git_env(base / "home")
    root = base / tree.name
    build_tree(root, tree.pages, env)
    every = check(root, frozenset(Rule), env)
    default = check(root, ENFORCED, env)

    want = expected(tree)
    got = {finding.place() for finding in every.findings}
    problems = [f"{tree.name}: not reported: {p}:{n}: {rule.value}" for p, n, rule in want - got]
    problems += [f"{tree.name}: not expected: {i}" for i in every.findings if i.place() not in want]

    # The default run: the same findings, but those of the rules it leaves off.
    by_default = {finding.place() for finding in default.findings}
    if by_default != {item for item in got if item[2] in ENFORCED}:
        problems.append(f"{tree.name}: a default run does not report exactly the enforced rules")
    return problems, len(want)


def selftest() -> int:
    """Each rule, the ones off by default too, reports its crafted violations under its own id
    and nothing else; the clean tree meets every limit; an empty tree is a finding for each
    layout rule; a default run leaves out the rules it does not enforce."""
    start = time.perf_counter()
    problems: list[str] = []
    planted = 0
    with tempfile.TemporaryDirectory(prefix=f"{NAME}-") as name:
        for tree in SELFTEST_TREES:
            found, count = prove(tree, Path(name))
            problems += found
            planted += count

    for problem in sorted(problems):
        print(f"{NAME}: selftest: {problem}")
    if problems:
        return FOUND

    print(
        f"{NAME}: selftest: {planted} crafted findings in {len(SELFTEST_TREES)} trees under"
        f" {len(Rule)} rules, the clean pages clean; off by default: {rules_off()}"
        f" ({time.perf_counter() - start:.2f} s)"
    )
    return CLEAN


def run(root: Path) -> int:
    """Checks the repository's public Markdown with the rules a default run enforces."""
    start = time.perf_counter()
    report = check(root, ENFORCED, git_env())
    for finding in report.findings:
        print(finding)

    print(
        f"{NAME}: {report.pages} pages, {report.links} links, {len(report.findings)} findings;"
        f" off: {rules_off()} ({time.perf_counter() - start:.2f} s)",
        file=sys.stderr,
    )
    return FOUND if report.findings else CLEAN


def main() -> int:
    parser = argparse.ArgumentParser(prog="check-docs.py", description=__doc__.splitlines()[0])
    parser.add_argument(
        "command", nargs="?", choices=("selftest",), help="prove every rule on a crafted tree"
    )
    args = parser.parse_args()
    try:
        return selftest() if args.command == "selftest" else run(ROOT)
    except UsageError as error:
        print(f"{NAME}: {error}", file=sys.stderr)
        return USAGE


if __name__ == "__main__":
    sys.exit(main())
