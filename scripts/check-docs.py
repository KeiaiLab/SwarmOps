def git_env() -> dict[str, str]:
    """The environment for git, without the GIT_* variables that a git hook sets: they would
    point it at another repository or index."""
    return {name: value for name, value in os.environ.items() if not name.startswith("GIT_")}


def bare_git_env(home: Path) -> dict[str, str]:
    """git_env() without the user's and the system's git configuration and ignore files, which
    must not hide a page of the selftest's tree."""
    return git_env() | {
        "GIT_CONFIG_GLOBAL": os.devnull,
        "GIT_CONFIG_NOSYSTEM": "1",
        "HOME": str(home),
        "XDG_CONFIG_HOME": str(home),
    }


def git_files(root: Path, env: dict[str, str]) -> frozenset[str]:
    """The files of the repository at `root`, as paths from it: tracked, or untracked and not
    ignored, and present in the work tree."""
    try:
        done = subprocess.run(GIT_FILES, cwd=root, env=env, capture_output=True, check=False)
    except FileNotFoundError as error:
        raise UsageError(f"git is needed to list the repository's files: {error}") from error
    if done.returncode != 0:
        raise UsageError(f"git ls-files failed: {done.stderr.decode(errors='replace').strip()}")

    names = done.stdout.decode("utf-8", "surrogateescape").split("\0")
    return frozenset(name for name in names if name and (root / name).is_file())


def ancestors(files: frozenset[str]) -> frozenset[str]:
    """Every directory that holds a file, as a path from the root ("." for the root itself)."""
    dirs = {"."}
    for name in files:
        parent = posixpath.dirname(name)
        while parent and parent not in dirs:
            dirs.add(parent)
            parent = posixpath.dirname(parent)
    return frozenset(dirs)


class Repo:
    """The repository's files, with each page's text, prose and anchors read once."""

    def __init__(self, root: Path, env: dict[str, str]) -> None:
        self.root = root
        self.files = git_files(root, env)
        self.dirs = ancestors(self.files)
        self._texts: dict[str, str] = {}
        self._prose: dict[str, str] = {}
        self._anchors: dict[str, frozenset[str]] = {}

    def text(self, path: str) -> str:
        if path not in self._texts:
            try:
                self._texts[path] = (self.root / path).read_text(encoding="utf-8")
            except UnicodeDecodeError as error:
                raise UsageError(f"{path}: not UTF-8: {error}") from error
        return self._texts[path]

    def prose(self, path: str) -> str:
        if path not in self._prose:
            self._prose[path] = mask(self.text(path))
        return self._prose[path]

    def anchors(self, path: str) -> frozenset[str]:
        if path not in self._anchors:
            self._anchors[path] = page_anchors(self.text(path), self.prose(path))
        return self._anchors[path]


def fenced(lines: list[str]) -> set[int]:
    """The indexes of the lines in fenced code blocks, fences included. A fence closes at a line
    of the same character, at least as long, with nothing after it; an unclosed one runs on to
    the end."""
    inside: set[int] = set()
    fence = ""
    for index, line in enumerate(lines):
        found = FENCE.fullmatch(line)
        if not fence:
            # Backticks with a backtick in the info string open no fence: they are inline code.
            if found and not (found[1][0] == "`" and "`" in found[2]):
                fence = found[1]
                inside.add(index)
            continue

        inside.add(index)
        if not found or found[2].strip():
            continue
        if found[1][0] == fence[0] and len(found[1]) >= len(fence):
            fence = ""
    return inside


def span_end(text: str, run: re.Match[str]) -> int | None:
    """Where the code span that the backtick `run` opens ends: after the next run of as many
    backticks in its paragraph. None when there is none, and the backticks are literal."""
    gap = BLANK_LINE.search(text, run.end())
    limit = gap.start() if gap else len(text)
    for other in BACKTICKS.finditer(text, run.end(), limit):
        if len(other.group()) == len(run.group()):
            return other.end()
    return None


def code_spans(text: str) -> list[tuple[int, int]]:
    """The (start, end) of every inline code span."""
    spans = []
    position = 0
    while run := BACKTICKS.search(text, position):
        end = span_end(text, run)
        if end is None:
            position = run.end()
            continue
        spans.append((run.start(), end))
        position = end
    return spans


def blank(text: str, spans: list[tuple[int, int]]) -> str:
    """The text with each (start, end) span turned into spaces, its newlines kept, so that
    offsets and line numbers stay as they were."""
    if not spans:
        return text
    chars = list(text)
    for start, end in spans:
        for index in range(start, end):
            if chars[index] != "\n":
                chars[index] = " "
    return "".join(chars)


def mask(text: str) -> str:
    """The prose of a page: its code blocks, code spans and HTML comments blanked, which GitHub
    renders without links or headings."""
    lines = text.split("\n")
    for index in fenced(lines):
        lines[index] = " " * len(lines[index])

    prose = "\n".join(lines)
    prose = blank(prose, code_spans(prose))
    return blank(prose, [found.span() for found in COMMENT.finditer(prose)])


def setext_text(lines: list[str], fence: set[int], index: int) -> tuple[int, str] | None:
    """The first line and the text of the setext heading that line `index` underlines: its
    whole paragraph, in the same block quote, lines joined with nothing between. `Exit`,
    `codes`, `-----` gives `Exitcodes`. None when no paragraph ends just above, or when the
    paragraph continues a list item, quote, table or HTML block."""
    depth = len(QUOTES.match(lines[index])[0])
    first = index
    while first:
        line = lines[first - 1]
        inner = line[len(QUOTES.match(line)[0]):]

        # 1. A blank line, a fence, a heading or a rule ends the paragraph above: it starts here.
        if first - 1 in fence or not inner.strip() or ATX.fullmatch(inner):
            break
        if SETEXT.fullmatch(inner):
            break

        # 2. Any other block continues into the lines here, so they are no heading's text.
        if NOT_TEXT.match(inner) or len(QUOTES.match(line)[0]) != depth:
            return None
        first -= 1

    if first == index:
        return None
    words = [line[len(QUOTES.match(line)[0]):].strip() for line in lines[first:index]]
    return first, "".join(words)


def md_headings(text: str, prose: str) -> list[tuple[int, str]]:
    """The offset and text of each Markdown heading: ATX (`## Name`) and setext (a paragraph
    underlined with `===` or `---`), in block quotes and list items too. The prose finds them,
    so that headings in code and comments do not count; the text gives their words."""
    lines = text.split("\n")
    masked = prose.split("\n")
    fence = fenced(lines)
    starts = line_starts(text)
    found = []
    for index, line in enumerate(masked):
        # 1. An ATX heading, after any container markers: `> ## In short`, `- ## Step one`.
        cut = len(CONTAINERS.match(lines[index])[0])
        atx = ATX.fullmatch(line[cut:]) and ATX.fullmatch(lines[index][cut:])
        if atx:
            found.append((starts[index], plain(atx[2] or "")))
            continue

        # 2. A setext underline, in a block quote or not: its paragraph is the heading.
        cut = len(QUOTES.match(lines[index])[0])
        if index in fence or not SETEXT.fullmatch(line[cut:]):
            continue
        heading = setext_text(lines, fence, index)
        if heading:
            found.append((starts[heading[0]], plain(heading[1])))
    return found


def html_headings(text: str, prose: str) -> list[tuple[int, str]]:
    """The offset and text of each HTML heading, `<h1>` to `<h6>`, which GitHub anchors too.
    Nothing inside one is rendered as Markdown."""
    found = []
    for heading in HTML_HEADING.finditer(prose):
        inner = text[heading.start(2):heading.end(2)]
        found.append((heading.start(), html.unescape(HTML_TAG.sub("", inner))))
    return found


def code_text(code: str) -> str:
    """A code span's content: one space comes off each end when both ends have one."""
    if code.startswith(" ") and code.endswith(" ") and code.strip():
        return code[1:-1]
    return code


class Flank(enum.Enum):
    """How CommonMark sees the character beside a delimiter run."""

    SPACE = "space"
    PUNCT = "punct"
    WORD = "word"


def flank(char: str) -> Flank:
    """The kind of `char`: a line's end is a space; a code span's backtick and an escape count
    as punctuation."""
    if not char or char.isspace():
        return Flank.SPACE
    if char == KEPT_UNDERSCORE or CODE_MARKS.fullmatch(char):
        return Flank.PUNCT
    if unicodedata.category(char).startswith("P") or (char.isascii() and not char.isalnum()):
        return Flank.PUNCT
    return Flank.WORD


@dataclass
class Delimiter:
    """A run of `_`: where it is, how many of its characters remain, and what it can do."""

    start: int
    length: int
    size: int
    opens: bool
    closes: bool


def delimiters(text: str) -> list[Delimiter]:
    """The `_` runs of `text`, each with CommonMark's flanking rules for `_`: it opens only when
    left-flanking and not inside a word, and closes the same way round."""
    runs = []
    for run in UNDERSCORES.finditer(text):
        before = flank(text[run.start() - 1] if run.start() else "")
        after = flank(text[run.end()] if run.end() < len(text) else "")
        left = after != Flank.SPACE and (after != Flank.PUNCT or before != Flank.WORD)
        right = before != Flank.SPACE and (before != Flank.PUNCT or after != Flank.WORD)
        size = len(run.group())
        opens = left and (not right or before == Flank.PUNCT)
        closes = right and (not left or after == Flank.PUNCT)
        runs.append(Delimiter(run.start(), size, size, opens, closes))
    return runs


def odd_match(opener: Delimiter, closer: Delimiter) -> bool:
    """CommonMark's rule of 3: a run that both opens and closes pairs with another only when
    their sizes do not add up to a multiple of 3, unless both sizes are."""
    if not (opener.closes or closer.opens):
        return False
    both = opener.size % 3 == 0 and closer.size % 3 == 0
    return (opener.size + closer.size) % 3 == 0 and not both


def strip_emphasis(text: str) -> str:
    """The text without the `_` that pair up as emphasis, as CommonMark pairs them: `_emph_`
    and `__strong__` go, while `snake_case`, `the _id field` and `foo_` keep theirs."""
    runs = delimiters(text)
    stack: list[Delimiter] = []
    for closer in runs:
        # 1. Pair the closer with the nearest opener below it, as often as both have characters.
        while closer.closes and closer.length:
            at = next(
                (i for i in range(len(stack) - 1, -1, -1) if not odd_match(stack[i], closer)), None
            )
            if at is None:
                break
            opener = stack[at]
            used = 2 if opener.length >= 2 and closer.length >= 2 else 1
            opener.length -= used
            closer.length -= used
            del stack[at + 1:]
            if not opener.length:
                stack.pop()

        # 2. A run with characters left that can open waits for a closer.
        if closer.length and closer.opens:
            stack.append(closer)

    # 3. Each run keeps the characters no pair used.
    parts = []
    position = 0
    for run in runs:
        parts.append(text[position:run.start] + "_" * run.length)
        position = run.start + run.size
    parts.append(text[position:])
    return "".join(parts)


def inline_text(markdown: str) -> str:
    """A heading's Markdown, its code spans each one CODE_MARKS character, as text: comments,
    images, tags and emphasis dropped, links by their text, autolinks by their URL, escapes and
    entities resolved."""
    text = COMMENT.sub("", markdown)
    text = IMAGE.sub("", text)
    text = LINK_TEXT.sub(r"\1", text)
    text = AUTOLINK.sub(r"\1", text)
    text = HTML_TAG.sub("", text)
    text = strip_emphasis(text.replace(ESCAPED_UNDERSCORE, KEPT_UNDERSCORE))
    text = MD_ESCAPE.sub(r"\1", text).replace(KEPT_UNDERSCORE, "_")
    return html.unescape(text)


def plain(markdown: str) -> str:
    """A heading's Markdown as the text GitHub renders: code spans word for word, also inside
    a link's text. `See [`land`](#x)` -> `See land`."""
    codes = []

    def mark(span: re.Match[str]) -> str:
        codes.append(code_text(span[2]))
        return chr(CODE_MARK + len(codes) - 1)

    def unmark(found: re.Match[str]) -> str:
        index = ord(found.group()) - CODE_MARK
        return codes[index] if index < len(codes) else found.group()

    text = inline_text(CODE_SPAN.sub(mark, markdown))
    return CODE_MARKS.sub(unmark, text)


def slug_keeps(char: str) -> bool:
    """Whether GitHub's slug keeps a character of a heading's lower-cased text."""
    category = unicodedata.category(char)
    if char in SLUG_KEEP_CHARS or category in SLUG_KEEP_CATEGORIES:
        return True
    return category[0] in SLUG_KEEP_CLASSES


def slugify(text: str) -> str:
    """GitHub's anchor for a heading's text: each character lower-cased on its own (`ΣΑΣ` ->
    `σασ`), all but SLUG_KEEP_CATEGORIES, `-` and spaces dropped, each space a `-`.
    `The API (v2)` -> `the-api-v2`, `① Install` -> `-install`."""
    lower = "".join(char.lower() for char in text)
    return "".join(char for char in lower if slug_keeps(char)).replace(" ", "-")


def unique(slug: str, seen: dict[str, int]) -> str:
    """`slug`, or `slug-1`, `slug-2` ... when it is taken, as GitHub numbers repeated headings."""
    base = slug
    while slug in seen:
        seen[base] += 1
        slug = f"{base}-{seen[base]}"
    seen[slug] = 0
    return slug


def page_anchors(text: str, prose: str) -> frozenset[str]:
    """The fragments a page answers to: its headings' slugs, numbered in page order, and its
    `<a id>` and `<a name>`."""
    seen: dict[str, int] = {}
    found = set()
    for _, heading in sorted(md_headings(text, prose) + html_headings(text, prose)):
        slug = slugify(heading)
        if slug:
            found.add(unique(slug, seen))

    found.update(named[1] for named in NAMED_ANCHOR.finditer(prose))
    return frozenset(found)


def dest_end(text: str, start: int) -> int:
    """The end of a bare link destination: at a space, or at a `)` that closes no `(` in it."""
    depth = 0
    index = start
    while index < len(text):
        char = text[index]
        if char == "\\":
            index += 2
            continue
        if char.isspace() or char < " ":
            break
        if char == "(":
            depth += 1
        if char == ")":
            if not depth:
                break
            depth -= 1
        index += 1
    return min(index, len(text))


def parse_dest(text: str, position: int) -> tuple[int, str] | None:
    """The offset and destination of the inline link whose `](` ends at `position`. None when
    no destination follows, as in `f(x)[y](a b)`."""
    start = LEADING_BLANK.match(text, position).end()
    if text.startswith("<", start):
        end = text.find(">", start)
        if end < 0 or "\n" in text[start:end]:
            return None
        dest, after = text[start + 1:end], end + 1
    else:
        after = dest_end(text, start)
        dest = text[start:after]

    if not LINK_TAIL.match(text, after):
        return None
    return start, MD_ESCAPE.sub(r"\1", dest)


def attr_links(prose: str) -> list[tuple[int, str]]:
    """The URLs in HTML tags' href, src and srcset attributes, with their offsets."""
    found = []
    for tag in TAG.finditer(prose):
        for attr in URL_ATTR.finditer(tag.group()):
            group = next(index for index in (2, 3, 4) if attr[index] is not None)
            offset = tag.start() + attr.start(group)
            if attr[1].lower() != "srcset":
                found.append((offset, attr[group].strip()))
                continue
            # srcset: comma-separated candidates, each a URL and an optional descriptor.
            for candidate in attr[group].split(","):
                if candidate.strip():
                    found.append((offset, candidate.split()[0]))
    return found


def trim_url(url: str) -> str:
    """A bare URL without what GitHub leaves out of its autolinks: trailing punctuation, and a
    `)` that closes no `(` in it."""
    url = url.rstrip(URL_TRAILER)
    while url.endswith(")") and url.count("(") < url.count(")"):
        url = url[:-1].rstrip(URL_TRAILER)
    return url


def page_links(prose: str) -> list[tuple[int, str]]:
    """Every link destination of a page's prose, with its offset: inline links and images,
    reference definitions, autolinks, HTML attributes and bare URLs."""
    found = []
    for opener in INLINE_LINK.finditer(prose):
        parsed = parse_dest(prose, opener.end())
        if parsed:
            found.append(parsed)
    for definition in REF_DEF.finditer(prose):
        found.append((definition.start(1), definition[1].removeprefix("<").removesuffix(">")))
    for autolink in AUTOLINK.finditer(prose):
        found.append((autolink.start(1), autolink[1]))
    found += attr_links(prose)

    # A bare URL GitHub links by itself, unless it is the destination just read.
    taken = {offset for offset, _ in found}
    for bare in BARE_URL.finditer(prose):
        if bare.start() not in taken:
            found.append((bare.start(), trim_url(bare.group())))
    return found


def check_url(url: str) -> str | None:
    """A URL outside the repository: its syntax only, never a request."""
    if any(char.isspace() for char in url):
        return f"a space in the URL {url}"
    try:
        parts = urllib.parse.urlsplit(url)
        _ = parts.port  # raises ValueError on a malformed port
    except ValueError as error:
        return f"malformed URL {url}: {error}"

    scheme = parts.scheme.lower()
    if scheme == MAIL_SCHEME:
        return None if MAILBOX.fullmatch(parts.path) else f"malformed address in {url}"
    if scheme not in WEB_SCHEMES:
        return f"unsupported scheme in {url}"
    if not HOSTNAME.fullmatch(parts.hostname or ""):
        return f"malformed host in {url}"
    return None


def line_count(repo: Repo, path: str) -> int:
    """The lines of a file as GitHub numbers them, its last newline ending the last line."""
    data = (repo.root / path).read_bytes()
    return data.count(b"\n") + (0 if not data or data.endswith(b"\n") else 1)


def check_lines(repo: Repo, target: str, fragment: str) -> str | None:
    """A fragment into a file GitHub shows as source: a line anchor within the file."""
    lines = LINE_ANCHOR.fullmatch(fragment)
    if not lines:
        return f"#{fragment}: {target} is not Markdown, so only a line anchor (#L12) fits it"
    first, last = int(lines[1]), int(lines[2] or lines[1])
    count = line_count(repo, target)
    if 1 <= first <= last <= count:
        return None
    return f"#{fragment}: {target} has {count} lines"


def check_anchor(repo: Repo, target: str, fragment: str) -> str | None:
    """A fragment of a link into the repository: a heading or named anchor of the target, or
    of the README GitHub shows for a directory; a line anchor into any other file."""
    if not fragment:
        return None
    if target in repo.dirs:
        readme = posixpath.normpath(posixpath.join(target, README))
        if readme not in repo.files:
            return f"#{fragment}: {target}/ has no {README} to hold it"
        target = readme

    if not target.endswith(".md"):
        return check_lines(repo, target, fragment)
    if fragment in repo.anchors(target):
        return None
    return f"no anchor #{fragment} in {target}"


def check_path(repo: Repo, source: str, dest: str) -> str | None:
    """A link into the repository: from `source`'s directory, or from the root when it starts
    with `/`, as GitHub resolves it."""
    path, _, fragment = dest.partition("#")
    path = urllib.parse.unquote(path.partition("?")[0])
    fragment = urllib.parse.unquote(fragment)
    if not path:
        return check_anchor(repo, source, fragment)

    base = "" if path.startswith("/") else posixpath.dirname(source)
    target = posixpath.normpath(posixpath.join(base, path.lstrip("/")))
    if target == ".." or target.startswith("../"):
        return f"{dest} points outside the repository"
    if target in repo.files or target in repo.dirs:
        return check_anchor(repo, target, fragment)
    if (repo.root / target).exists():
        return f"{target} is ignored by git, so not in the repository"
    return f"no such file: {target}"


def check_dest(repo: Repo, source: str, dest: str) -> str | None:
    """What is wrong with a link destination of `source`, if anything."""
    if not dest:
        return "a link without a target"
    in_repo = REPO_URL.fullmatch(dest)
    if in_repo:
        return check_path(repo, source, "/" + in_repo[1] + (in_repo[2] or ""))
    if dest.startswith("//"):
        return check_url("https:" + dest)
    if SCHEME.match(dest):
        return check_url(dest)
    return check_path(repo, source, dest)


def host_paths(line: str) -> list[str]:
    """The host paths in a line, but the examples' home."""
    return [path.group() for path in HOST_PATH.finditer(line) if path[1] not in EXAMPLE_HOMES]


def citations(repo: Repo, line: str) -> list[str]:
    """What in a line cites the private design documents."""
    found = [f"a section sign ({SECTION_SIGN})"] if SECTION_SIGN in line else []
    for docs in DOCS_DIR.finditer(line):
        if f"docs/{docs[1]}" not in repo.dirs:
            found.append(f"{docs.group()}, which the repository does not have")
    return found


def line_rules(repo: Repo, line: str, rules: frozenset[Rule]) -> list[tuple[Rule, str]]:
    """The findings of the rules that read a line on its own, code included."""
    found = []
    if Rule.HOST_PATHS in rules:
        found += [(Rule.HOST_PATHS, f"host path {path}") for path in host_paths(line)]
    if Rule.SPEC_CITATIONS in rules:
        found += [(Rule.SPEC_CITATIONS, f"cites {what}") for what in citations(repo, line)]
    if Rule.TRACES in rules:
        for pattern in TRACES:
            trace = pattern.search(line)
            if trace:
                found.append((Rule.TRACES, f"trace: {trace.group()}"))
    return found


def line_starts(text: str) -> list[int]:
    """The offset of each line's first character."""
    return [0] + [newline.end() for newline in NEWLINE.finditer(text)]


def line_at(starts: list[int], offset: int) -> int:
    """The 1-based number of the line that holds `offset`."""
    return bisect_right(starts, offset)


def sentences(text: str) -> list[tuple[int, str]]:
    """Each sentence of the text's paragraphs, lower-cased with its whitespace collapsed, and
    the line it starts on."""
    starts = line_starts(text)
    found = []
    for paragraph in PARAGRAPH.finditer(text):
        for sentence in SENTENCE.finditer(paragraph.group()):
            offset = paragraph.start() + sentence.start()
            found.append((line_at(starts, offset), " ".join(sentence.group().split()).lower()))
    return found


def wording(text: str) -> list[tuple[int, str]]:
    """The sentences that still describe a private repository."""
    found = []
    for line, sentence in sentences(text):
        if PRIVATE_REPOSITORY.search(sentence):
            found.append((line, "calls the repository private"))
        elif FREE_PLAN.search(sentence) and PRIVATE.search(sentence):
            found.append((line, "names the Free plan and private together"))
    return found


def missing_marker(path: str, text: str) -> bool:
    """A generated reference page that does not start with its marker."""
    if not path.startswith(REFERENCE_DIR) or path.startswith(REFERENCE_NOTES):
        return False
    if path in REFERENCE_HAND_WRITTEN:
        return False
    return not text.removeprefix(BOM).startswith(GENERATED_MARKER)


def check_page(repo: Repo, path: str, rules: frozenset[Rule], report: Report) -> None:
    """Every rule on one Markdown page."""
    text = repo.text(path)
    starts = line_starts(text)
    report.pages += 1

    # Links, from the prose: GitHub links nothing in code or comments.
    if Rule.LINKS in rules:
        for offset, dest in page_links(repo.prose(path)):
            report.links += 1
            problem = check_dest(repo, path, dest)
            if problem:
                report.findings.append(Finding(path, line_at(starts, offset), Rule.LINKS, problem))

    # Text rules, from every line: code is published too.
    for number, line in enumerate(text.split("\n"), 1):
        for rule, message in line_rules(repo, line, rules):
            report.findings.append(Finding(path, number, rule, message))
    if Rule.PRIVATE_WORDING in rules:
        for number, message in wording(text):
            report.findings.append(Finding(path, number, Rule.PRIVATE_WORDING, message))
    if Rule.GENERATED_MARKER in rules and missing_marker(path, text):
        message = f"the first line is not the `{GENERATED_MARKER} ...` comment"
        report.findings.append(Finding(path, 1, Rule.GENERATED_MARKER, message))


def check_template(repo: Repo, path: str, rules: frozenset[Rule], report: Report) -> None:
    """The `url:` values of an issue template: GitHub shows them as links."""
    for number, line in enumerate(repo.text(path).split("\n"), 1):
        value = URL_VALUE.match(line)
        if not value:
            continue
        if Rule.LINKS in rules:
            report.links += 1
            problem = check_dest(repo, path, value[1])
            if problem:
                report.findings.append(Finding(path, number, Rule.LINKS, problem))
        for rule, message in line_rules(repo, value[1], rules):
            report.findings.append(Finding(path, number, rule, message))


def rules_off() -> str:
    """The ids of the rules a default run leaves off."""
    return ", ".join(sorted(rule.value for rule in set(Rule) - ENFORCED)) or "none"


def check(root: Path, rules: frozenset[Rule], env: dict[str, str]) -> Report:
    """Runs `rules` over the public Markdown of the repository at `root`, git run with `env`."""
    repo = Repo(root, env)
    report = Report()
    for path in sorted(repo.files):
        if PUBLIC_PAGE.fullmatch(path) or path in EXTRA_PAGES:
            check_page(repo, path, rules, report)
        elif ISSUE_TEMPLATE.fullmatch(path):
            check_template(repo, path, rules, report)
    report.findings.sort(key=Finding.key)
    return report


