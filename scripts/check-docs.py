class UsageError(Exception):
    """A run that cannot check the tree: no git, no work tree, a page that is not UTF-8."""


@dataclass(frozen=True)
class Finding:
    """One finding: where, under which rule, and what."""

    path: str
    line: int
    rule: Rule
    message: str

    def __str__(self) -> str:
        return f"{self.path}:{self.line}: {self.rule.value}: {self.message}"

    def key(self) -> tuple[str, int, str, str]:
        return self.path, self.line, self.rule.value, self.message

    def place(self) -> tuple[str, int, Rule]:
        return self.path, self.line, self.rule


