def page_opening(repo: Repo, path: str, need: Need) -> list[Finding]:
    """The title, then a paragraph of at most GUIDE_OPENING_MAX words; then, when the page
    needs it, a `**You need:**` paragraph before the first `##` that names a release."""
    rule = Rule.GUIDE_OPENING
    if path not in repo.files:
        return missing(path, rule)
    parts = blocks(repo.text(path))
    if not parts or not is_title(parts[0]):
        return [Finding(path, 1, rule, "the page does not open with its `# ` title")]

    # 1. The opening paragraph.
    found = []
    words = 0
    opening = parts[1] if len(parts) > 1 else None
    if not opening or opening.kind != Kind.PARAGRAPH or opening.text.startswith(NEED_LABEL):
        line = opening.line + 1 if opening else 1
        found.append(Finding(path, line, rule, "the title is not followed by a paragraph"))
    else:
        words = word_count(opening.text)
    if words > GUIDE_OPENING_MAX:
        message = f"the opening has {words} words; at most {GUIDE_OPENING_MAX}"
        found.append(Finding(path, opening.line + 1, rule, message))

    # 2. What the reader needs, before the first `##`.
    if need == Need.ABSENT:
        return found
    return found + need_block(path, parts, words)


def need_block(path: str, parts: list[Block], opening: int) -> list[Finding]:
    """The `**You need:**` paragraph: before the first heading, naming a release, and with
    the opening at most GUIDE_HEAD_MAX words."""
    rule = Rule.GUIDE_OPENING
    before = itertools.takewhile(lambda block: block.kind != Kind.HEADING, parts[1:])
    need = next((block for block in before if block.text.startswith(NEED_LABEL)), None)
    if need is None:
        return [Finding(path, 1, rule, f"no `{NEED_LABEL}` paragraph before the first `##`")]

    found = []
    if not versions(need.text):
        found.append(Finding(path, need.line + 1, rule, f"`{NEED_LABEL}` names no release"))
    total = opening + word_count(need.text)
    if total > GUIDE_HEAD_MAX:
        message = f"opening and `{NEED_LABEL}` have {total} words; at most {GUIDE_HEAD_MAX}"
        found.append(Finding(path, need.line + 1, rule, message))
    return found


