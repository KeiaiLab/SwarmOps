def settings_claim(repo: Repo) -> list[Finding]:
    """The settings file's description: short, and no `git replacement` (GH2, GH20)."""
    rule = Rule.CLAIM
    if SETTINGS not in repo.files:
        return missing(SETTINGS, rule)
    text = repo.text(SETTINGS)
    try:
        value = description(json.loads(text))
    except json.JSONDecodeError as error:
        return [Finding(SETTINGS, error.lineno, rule, f"not JSON: {error.msg}")]
    if not isinstance(value, str) or not value.strip():
        return [Finding(SETTINGS, 1, rule, "no description")]

    lines = text.split("\n")
    line = next((i + 1 for i, other in enumerate(lines) if '"description"' in other), 1)
    found = []
    if CLAIM.search(value):
        found.append(Finding(SETTINGS, line, rule, "the description says `git replacement`"))
    words = len(value.split())
    if words > DESCRIPTION_MAX_WORDS or len(value) > DESCRIPTION_MAX_CHARS:
        message = (
            f"the description has {words} words and {len(value)} characters; at most"
            f" {DESCRIPTION_MAX_WORDS} and {DESCRIPTION_MAX_CHARS}"
        )
        found.append(Finding(SETTINGS, line, rule, message))
    return found


