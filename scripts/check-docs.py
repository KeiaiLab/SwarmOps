"""Checks the public Markdown, offline: links and anchors, host paths, citations, traces, wording.

    python3 -I scripts/check-docs.py           # checks the tree; exit 1 on a finding
    python3 -I scripts/check-docs.py selftest  # proves every rule on a crafted tree

The public Markdown is what git tracks or would track, so the files it ignores (the maintainers'
local documents among them) stay out: the root's `*.md`, `docs/**/*.md`, `.github/**/*.md`,
scripts/site/README.md and bench/compare/README.md, and the `url:` values of
.github/ISSUE_TEMPLATE/*.yml. A finding prints as `path:line: rule: message`. Exit 0 when clean,
1 on a finding, 2 on a usage error. It needs Python 3.11 or newer and git, and no network.

The rules, by the id a finding prints:

  links             A relative link, reference definition or HTML href, src or srcset names a
                    file or directory of the repository, and its fragment a heading there (by
                    GitHub's slugs; headings in code fences do not count) or an `<a id|name>`.
                    A github.com/KeiaiLab/SwarmOps blob/stable or tree/stable URL is checked the
                    same way, any other URL for its syntax only.
  host-paths        No path of a host: a home directory but the examples' /home/me, /data/,
                    /mnt/c/.
  spec-citations    No section sign, and no `docs/<dir>/` that the repository lacks: the public
                    text cites public anchors, not the private design documents.
  traces            No attribution or tool trace: a co-author trailer or generator footer that
                    names the assistant, its vendor's commit address, a model id.
  private-wording   No sentence that calls the repository private, or names the Free plan and
                    private together.
  generated-marker  A generated page of docs/reference/ (not notes/, not the hand-written
                    pages) starts with `<!-- Generated by`.

A default run enforces the rules ENFORCED names; `selftest` runs them all.
"""

