def expected() -> frozenset[tuple[str, int, Rule]]:
    """Every (path, line, rule) the selftest's tree must report, and nothing else."""
    found = set(SELFTEST_EXTRA)
    for path, text in SELFTEST_PAGES.items():
        stem = posixpath.splitext(posixpath.basename(path))[0]
        rule = next((rule for rule in Rule if rule.value == stem), None)
        if rule is None:
            continue
        for number, line in enumerate(text.split("\n"), 1):
            if line.strip():
                found.add((path, number, rule))
    return frozenset(found)


def build_tree(root: Path, env: dict[str, str]) -> None:
    """Writes the selftest's tree into an empty git repository at `root`."""
    for path, text in SELFTEST_PAGES.items():
        file = root / path
        file.parent.mkdir(parents=True, exist_ok=True)
        file.write_text(text, encoding="utf-8")
    try:
        subprocess.run(GIT_INIT, cwd=root, env=env, capture_output=True, check=True)
    except (FileNotFoundError, subprocess.CalledProcessError) as error:
        raise UsageError(f"git init failed: {error}") from error


def selftest() -> int:
    """Each rule, the ones off by default too, reports its crafted violations under its own id
    and nothing else, and a default run leaves out the rules it does not enforce."""
    start = time.perf_counter()
    with tempfile.TemporaryDirectory(prefix=f"{NAME}-") as name:
        root = Path(name) / "tree"
        env = bare_git_env(Path(name) / "home")
        build_tree(root, env)
        every = check(root, frozenset(Rule), env)
        default = check(root, ENFORCED, env)

    want = expected()
    got = {finding.place() for finding in every.findings}
    problems = [f"not reported: {path}:{line}: {rule.value}" for path, line, rule in want - got]
    problems += [f"not expected: {item}" for item in every.findings if item.place() not in want]

    # The default run: the same findings, but those of the rules it leaves off.
    by_default = {finding.place() for finding in default.findings}
    if by_default != {item for item in got if item[2] in ENFORCED}:
        problems.append("a default run does not report exactly the enforced rules' findings")
    for problem in sorted(problems):
        print(f"{NAME}: selftest: {problem}")
    if problems:
        return FOUND

    print(
        f"{NAME}: selftest: {len(want)} crafted findings under {len(Rule)} rules, the clean pages"
        f" clean; off by default: {rules_off()} ({time.perf_counter() - start:.2f} s)"
    )
    return CLEAN


def run(root: Path) -> int:
    """Checks the repository's public Markdown with the rules a default run enforces."""
    start = time.perf_counter()
    report = check(root, ENFORCED, git_env())
    for finding in report.findings:
        print(finding)

    print(
        f"{NAME}: {report.pages} pages, {report.links} links, {len(report.findings)} findings;"
        f" off: {rules_off()} ({time.perf_counter() - start:.2f} s)",
        file=sys.stderr,
    )
    return FOUND if report.findings else CLEAN


def main() -> int:
    parser = argparse.ArgumentParser(prog="check-docs.py", description=__doc__.splitlines()[0])
    parser.add_argument(
        "command", nargs="?", choices=("selftest",), help="prove every rule on a crafted tree"
    )
    args = parser.parse_args()
    try:
        return selftest() if args.command == "selftest" else run(ROOT)
    except UsageError as error:
        print(f"{NAME}: {error}", file=sys.stderr)
        return USAGE


if __name__ == "__main__":
    sys.exit(main())
