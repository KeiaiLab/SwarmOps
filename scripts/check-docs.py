"""Checks the public Markdown, offline: links and anchors, host paths, citations, traces, wording.

    python3 -I scripts/check-docs.py           # checks the tree; exit 1 on a finding
    python3 -I scripts/check-docs.py selftest  # proves every rule on a crafted tree

The public Markdown is what git tracks or would track, so the files it ignores (the maintainers'
local documents among them) stay out: the root's `*.md`, `docs/**/*.md`, `.github/**/*.md`,
scripts/site/README.md and bench/compare/README.md, and the `url:` values of
.github/ISSUE_TEMPLATE/*.yml. A finding prints as `path:line: rule: message`. Exit 0 when clean,
1 on a finding, 2 on a usage error. It needs Python 3.11 or newer and git, and no network.

The rules, by the id a finding prints:

  links             A relative link, reference definition or HTML href, src or srcset names a
                    file or directory of the repository, and its fragment a heading there (by
                    GitHub's slugs; headings in code fences do not count) or an `<a id|name>`.
                    A github.com/KeiaiLab/SwarmOps blob/stable or tree/stable URL is checked the
                    same way, any other URL for its syntax only.
  host-paths        No path of a host: a home directory but the examples' /home/me, /data/,
                    /mnt/c/.
  spec-citations    No section sign, and no `docs/<dir>/` that the repository lacks: the public
                    text cites public anchors, not the private design documents.
  traces            No attribution or tool trace: a co-author trailer or generator footer that
                    names the assistant, its vendor's commit address, a model id.
  private-wording   No sentence that calls the repository private, or names the Free plan and
                    private together.
  generated-marker  A generated page of docs/reference/ (not notes/, not the hand-written
                    pages) starts with `<!-- Generated by`.

The layout rules read README.md, the docs pages and repository files as a whole; a file or
section they need and cannot find is a finding. "Docs pages" are docs/**/*.md but the generated
reference and the pages FROZEN_DOCS names.

  readme-size       README.md: at most 300 lines, 2,000 words outside code, 45 lines a
                    section (the longest reported), 8 rows a table.
  readme-opening    README.md: a first sentence of at most 20 words without envelope,
                    changeset, land or store; no `git replacement` in the first 10 lines;
                    `## Install` and a platform line before line 60; a status statement that
                    names the workspace version; at most 4 badges, none a static one.
  readme-version    Each version in a README.md code block is the workspace version.
  entry-version     README, CONTRIBUTING, SECURITY, SUPPORT and the .github templates call no
                    other release current, latest, supported or the first release.
  readme-dated-list No README.md list item or table row with a date or a milestone id.
  praise-words      No praise word (fastest, best, robust ...) in README.md or a docs page,
                    unless its paragraph links docs/perf.md or docs/goals.md.
  claim             No `git replacement` in the settings file's description (at most 15
                    words, 120 characters), README's first 10 lines, or a docs page calling
                    SwarmOps one; docs/goals.md and docs/architecture.md are exempt.
  guide-opening     The guides, operate pages and five named pages open with a paragraph of
                    at most 40 words and a `**You need:**` paragraph naming a release (60
                    words together); docs/develop/style.md and docs/agents.md the paragraph.
  guide-next        The same pages end with `## Next`: one `**Next:**` line, 1 to 3 links,
                    each followed by text, each target present.
  docs-home         docs/README.md: an opening of at most 40 words, `## Start here` of at
                    most 6 short entries, six short organisation sentences, links to the
                    non-goals and the known limitations.
  install-failures  docs/guides/install.md, `## When the install does not work`: four cases,
                    each quoting a message scripts/install.sh prints.
  fence-label       Every code fence of a docs page names its language.
  no-prompt         No `$ ` or `% ` prompt in a shell code block of a docs page.
  callouts          Docs callouts: `> [!NOTE]`, `> [!WARNING]`, `> [!CAUTION]` only, at most
                    60 words each, 4 a page.
  perf-citations    Each figure with a unit of time or rate in README.md and docs/goals.md
                    has, in its table row or sentence, a link to a docs/perf.md anchor or a
                    quoted docs/perf.md section title (or its start, to a word's end).

A default run enforces the rules ENFORCED names; `selftest` runs them all.
"""

