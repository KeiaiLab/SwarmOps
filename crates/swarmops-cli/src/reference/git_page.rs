//! `docs/reference/coming-from-git.md`: git's commands and what to type instead, rendered from
//! [`ROWS`], the table the binary expands a git verb from and takes a refusal's hint from. So
//! the page, the aliases and the hints are one constant.
//!
//! ```text
//! gitlike::ROWS ─┬─▶ ## Tier 1, ## Tier 2    one row a git verb:
//!                │     | git | Class | What to type | `op` | Example | Hint when refused |
//!                └─▶ ### Notes               a verb's differences, and what is left for later
//! NOT_DONE ──────▶ ## What is not done
//! ```
//!
//! `coming_from_git_page_matches` fails when the committed page is not its rendering;
//! `SWARMOPS_REGEN_REFERENCE=1` with the ignored `regen_reference_git_page` writes it again, and
//! the documented `test(regen_reference)` filter matches that test too.

