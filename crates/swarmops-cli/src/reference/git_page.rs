/// The page's text.
fn render() -> String {
    let mut out = String::new();

    // 1. Title, the principle and what an alias is.
    let _ = writeln!(out, "{GENERATED}\n");
    let _ = writeln!(out, "# Coming from git\n");
    let _ = writeln!(
        out,
        "Where a SwarmOps operation does what a git command does, `{SO} <git verb>` runs it, \
         with git's flags where they mean the same. Where the meaning differs the command keeps \
         its own name (`land` is not `merge`), and the git verb is refused, exit 2, with one \
         line first in `error.hint` that names what to type. Nothing looks like git and does \
         something else: `{SO}` is not a drop-in for the git binary, and a line that ran before \
         git's verbs were read runs as it did.\n"
    );
    let _ = writeln!(
        out,
        "A git verb that runs is read as the command it stands for (`{SO} status` is \
         `{SO} ws status`): the envelope, its `op`, the help (`{SO} status --help`) and a usage \
         error are that command's, as [the CLI reference](cli.md) gives them. A store has no \
         working tree: `status`, `restore` and the bare forms of `diff`, `commit` and `rebase` \
         need a workspace. Their paths are read from the workspace's root, not from the working \
         directory as git's are; below the root a line that names paths is refused. The hints \
         here are written with `{SO}`; a hint names the program as it was run.\n"
    );

    // 2. Text instead of the envelope.
    let _ = writeln!(out, "## Text output\n");
    let _ = writeln!(
        out,
        "Every command prints one JSON envelope unless text is asked for. `--human` prints \
         text, in git's shape for `status`, `log`, `diff` and `commit`, and git's own shape \
         flags ask for it too (`{SO} status -s`, `{SO} log --oneline`, `{SO} diff --stat`). For \
         text from every command:\n"
    );
    let _ = writeln!(out, "```sh\nexport SWARMOPS_FORMAT=human\n```\n");

    // 3. How to read a row.
    let _ = writeln!(out, "## Classes\n");
    let _ = writeln!(out, "| Class | Meaning |\n| --- | --- |");
    for class in CLASSES {
        let _ = writeln!(out, "| {} | {} |", letter(class), cell(meaning(class)));
    }
    let _ = writeln!(
        out,
        "\nA row can carry two: one form of the verb runs, the others are refused with the \
         hint. `op` is the operation the example's envelope names; a row without one is \
         refused, and its example prints the hint.\n"
    );

    // 4. One table a tier, then the notes of its rows.
    tier(&mut out, Tier::One, "Tier 1", "everyday commands");
    tier(&mut out, Tier::Two, "Tier 2", "commands scripts and CI use");

    // 5. What the design leaves out on purpose.
    let _ = writeln!(out, "## What is not done\n");
    let _ = writeln!(out, "| Not done | Why | What to do |\n| --- | --- | --- |");
    for (what, why, instead) in NOT_DONE {
        let _ = writeln!(
            out,
            "| {} | {} | {} |",
            cell(what),
            cell(why),
            cell(instead)
        );
    }
    trim_end(out)
}

/// Every class, in the order the page explains them.
const CLASSES: [Class; 5] = [
    Class::Same,
    Class::Alias,
    Class::Different,
    Class::NoConcept,
    Class::Later,
];

/// A class's letter in the tables.
fn letter(class: Class) -> &'static str {
    match class {
        Class::Same => "S",
        Class::Alias => "A",
        Class::Different => "D",
        Class::NoConcept => "N",
        Class::Later => "L",
    }
}

/// What a class says of a git verb.
fn meaning(class: Class) -> &'static str {
    match class {
        Class::Same => "The same verb does the same.",
        Class::Alias => "The same verb, read as the SwarmOps command of the same meaning.",
        Class::Different => {
            "Different on purpose: the verb is refused, and the hint names what to type."
        }
        Class::NoConcept => "No such concept: the verb is refused, and the hint says what to do.",
        Class::Later => "A candidate for later: the notes say what would be built.",
    }
}

/// One tier's section, `name` the tier's and `what` its verbs: its table, then its notes.
fn tier(out: &mut String, tier: Tier, name: &str, what: &str) {
    let rows = || ROWS.iter().filter(move |row| row.tier == tier);

    // 1. One row a verb.
    let _ = writeln!(out, "## {name}: {what}\n");
    let _ = writeln!(out, "{HEADER}\n| --- | --- | --- | --- | --- | --- |");
    for row in rows() {
        let _ = writeln!(out, "{}", table_row(row));
    }

    // 2. The verbs that have something to add.
    let _ = writeln!(out, "\n### Notes on {}\n", name.to_lowercase());
    for row in rows() {
        let Some(note) = note(row) else {
            continue;
        };
        let _ = writeln!(out, "- **`git {}`**: {}", row.git, cell(&note));
    }
    out.push('\n');
}

/// A verb's row in its tier's table.
fn table_row(row: &Row) -> String {
    let classes: Vec<&str> = row.classes.iter().copied().map(letter).collect();
    let lines: Vec<String> = row.lines.iter().map(|line| code(&typed(line))).collect();
    let example = typed(row.example);
    let cells = [
        code(&format!("git {}", row.git)),
        classes.join(", "),
        or_empty(lines.join(BETWEEN)),
        or_empty(row.op.map(code).unwrap_or_default()),
        code(&example),
        or_empty(hint(row).map(|hint| code(&hint)).unwrap_or_default()),
    ];
    format!("| {} |", cells.join(" | "))
}

/// A verb's note with what is left for later, if it has either.
fn note(row: &Row) -> Option<String> {
    let later = row.later.map(|later| format!("Later: {later}."));
    let parts: Vec<&str> = [Some(row.note), later.as_deref()]
        .into_iter()
        .flatten()
        .filter(|part| !part.is_empty())
        .collect();
    (!parts.is_empty()).then(|| parts.join(" "))
}

/// The first line of a refusal's hint as the binary run as `so` prints it: `{so}` the name,
/// `{n}` the `n`th of the row's lines with it.
fn hint(row: &Row) -> Option<String> {
    Some(fill(row.hint?, row.lines))
}

/// `text` with its placeholders filled from `lines`.
fn fill(text: &str, lines: Lines) -> String {
    let named = text.replace(SO_SLOT, SO);
    let slots = lines.iter().enumerate();
    slots.fold(named, |text, (at, line)| {
        text.replace(&format!("{{{at}}}"), &typed(line))
    })
}

/// `words` as the line to type: the program's name first.
fn typed(words: &[&str]) -> String {
    format!("{SO} {}", words.join(" "))
}

/// `text` as a code span.
fn code(text: &str) -> String {
    format!("`{text}`")
}

/// `text`, or the mark of an empty cell.
fn or_empty(text: String) -> String {
    if text.is_empty() {
        return EMPTY.to_owned();
    }
    text
}

// ---- Tests ----

/// A line that is refused with the hint, for each verb whose example runs and that has a hint
/// for its other forms.
const REFUSED_FORMS: &[(&str, &str)] = &[
    ("restore", "restore"),
    ("tag", "tag v1"),
    ("reflog", "reflog"),
    ("worktree", "worktree add d"),
];

/// The first line where `want` and `got` differ, numbered from 1, with both versions.
fn first_difference(want: &str, got: &str) -> String {
    let mut want_lines = want.lines();
    let mut got_lines = got.lines();
    for number in 1.. {
        let (w, g) = (want_lines.next(), got_lines.next());
        if w.is_none() && g.is_none() {
            break;
        }
        if w != g {
            return format!(
                "line {number}:\n  generated: {}\n  committed: {}",
                w.unwrap_or("<end>"),
                g.unwrap_or("<end>")
            );
        }
    }
    "only line endings differ".to_owned()
}

/// The first hint line the layer gives `line`, typed as `so` at a workspace's root.
fn refused_with(line: &str) -> Option<String> {
    let args: Vec<OsString> = std::iter::once(SO)
        .chain(line.split_whitespace())
        .map(OsString::from)
        .collect();
    let place = || Place::Root;
    let Parsed::Usage {
        error, bin, path, ..
    } = gitlike::parse(&args, &place)
    else {
        panic!("{line:?} is not refused");
    };
    gitlike::hint(&error, &path, bin.as_deref(), &args, &place)
}

/// The committed page is what the code renders.
#[test]
fn coming_from_git_page_matches() {
    let text = render();
    let committed = fs::read_to_string(reference_dir().join(FILE)).unwrap_or_default();
    assert!(
        committed == text,
        "docs/reference/{FILE} is not what the code renders; run `{REGEN_CMD}`, review the diff \
         and commit it. First difference, {}",
        first_difference(&text, &committed)
    );
}

/// Writes the page again. Writes nothing unless `SWARMOPS_REGEN_REFERENCE=1` is set, so that
/// `--run-ignored all` never rewrites it.
#[test]
#[ignore = "writes docs/reference/coming-from-git.md when SWARMOPS_REGEN_REFERENCE=1; run on purpose"]
fn regen_reference_git_page() {
    if std::env::var_os(REGEN_VAR).is_none() {
        eprintln!("regen_reference_git_page: {REGEN_VAR} not set; nothing written");
        return;
    }
    fs::write(reference_dir().join(FILE), render()).unwrap();
}

/// Each hint on the page is the line the layer puts first in the refusal: of the row's example
/// where that is refused, of a refused form of the verb where the example runs.
#[test]
fn every_hint_is_the_layers() {
    for row in ROWS {
        let Some(on_page) = hint(row) else {
            continue;
        };
        let example = row.example.join(" ");
        let form = REFUSED_FORMS.iter().find(|(git, _)| *git == row.git);
        let line = match (row.op, form) {
            (None, _) => example.as_str(),
            (Some(_), Some((_, line))) => line,
            (Some(_), None) => panic!("{}: its example runs; name a refused form", row.git),
        };
        assert_eq!(refused_with(line), Some(on_page), "{line:?}");
    }
}

/// Every verb has its row in its tier's table, with six cells a code span cannot break.
#[test]
fn every_verb_has_its_row() {
    let text = render();
    for row in ROWS {
        let line = table_row(row);
        assert!(text.contains(&format!("\n{line}\n")), "{}: no row", row.git);
        assert_eq!(line.matches(" | ").count(), 5, "{line}");

        // A cell's code span holds no backtick or bar of its own.
        let spans = [typed(row.example), hint(row).unwrap_or_default()];
        let lines = row.lines.iter().map(|line| typed(line));
        for span in spans.into_iter().chain(lines) {
            assert!(!span.contains(['`', '|', '\n']), "{}: {span:?}", row.git);
        }
    }
}

/// The page is public text: it cites no design section and writes one name for the program.
#[test]
fn the_page_is_public_text() {
    let text = render();
    assert!(text.starts_with("<!-- Generated by"), "the marker is first");
    assert!(!text.contains('\u{a7}'), "the page cites a section");
    assert!(!text.contains(SO_SLOT), "a placeholder is left");
    assert!(!text.contains("{0}"), "a placeholder is left");
}

/// The filling itself: the name, each line by its place, and a text with no placeholder.
#[test]
fn a_hint_is_filled_from_its_lines() {
    let lines: Lines = &[&["ws", "land"], &["land", "HEAD"]];
    assert_eq!(
        fill("git merge: {0} or {1}; {so} op log", lines),
        "git merge: so ws land or so land HEAD; so op log"
    );
    assert_eq!(fill("git bisect: not built", &[]), "git bisect: not built");
}
