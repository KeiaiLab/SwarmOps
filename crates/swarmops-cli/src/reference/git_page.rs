/// The variable that makes `regen_reference_git_page` write the page.
const REGEN_VAR: &str = "SWARMOPS_REGEN_REFERENCE";

/// The command that writes the page again, as a failure names it.
const REGEN_CMD: &str = "SWARMOPS_REGEN_REFERENCE=1 cargo nextest run -p swarmops-cli \
--run-ignored ignored-only -E 'test(regen_reference)'";

/// The first line of the page.
const GENERATED: &str = "<!-- Generated by crates/swarmops-cli/src/reference/git_page.rs from \
the code: do not edit. Change the code, then run SWARMOPS_REGEN_REFERENCE=1 with the \
regen_reference_git_page test. -->";

/// The program's name as the page writes it.
const SO: &str = "so";

/// A hint's placeholder for the program's name.
const SO_SLOT: &str = "{so}";

/// A cell with nothing in it: a verb with no line to type, no operation or no hint.
const EMPTY: &str = "—";

/// What stands between two lines of one cell.
const BETWEEN: &str = " · ";

/// The header of a tier's table.
const HEADER: &str = "| git | Class | What to type | `op` | Example | Hint when refused |";

