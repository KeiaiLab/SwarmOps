/// One generated page: its path in `docs/reference/` and its text.
struct Page {
    name: String,
    text: String,
}

/// `docs/reference/`, from this crate's directory.
fn reference_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../docs/reference")
}

/// A tool's page name in [`DIR`]: `read_file` → `read-file.md`.
fn file_name(tool: &str) -> String {
    format!("{}.md", tool.replace('_', "-"))
}

/// Every page: the index, then one per tool in `tools/list`'s order.
fn pages() -> Vec<Page> {
    let golden = Golden::read();
    let commands = commands();
    let all = schema_for_all();

    // 1. The index.
    let mut pages = vec![Page {
        name: format!("{DIR}/{INDEX}"),
        text: index(&golden, &commands),
    }];

    // 2. One page per tool.
    for spec in &TOOLS {
        pages.push(Page {
            name: format!("{DIR}/{}", file_name(spec.name)),
            text: tool_page(spec, &golden, &commands, &all),
        });
    }
    pages
}

// ---- The CLI commands ----

/// Every command that names an operation, by its subcommand path, in the grammar's order.
fn commands() -> Vec<Vec<String>> {
    let mut grammar = Cli::command();
    grammar.build();
    let mut out = Vec::new();
    leaves(&grammar, &[], &mut out);
    out
}

/// The commands below `cmd`, whose path is `prefix`, into `out`.
fn leaves(cmd: &clap::Command, prefix: &[String], out: &mut Vec<Vec<String>>) {
    for sub in cmd.get_subcommands() {
        let mut path = prefix.to_vec();
        path.push(sub.get_name().to_owned());

        // A command that names an operation, before its own subcommands: `sync`, then
        // `sync status`. A group (`ref`, `op`, …) and clap's own `help` name none.
        if op_name(&path).is_some() {
            out.push(path.clone());
        }
        if sub.has_subcommands() {
            leaves(sub, &path, out);
        }
    }
}

/// The command that runs the operation of tool `name`: the one whose envelope `op` it is.
fn command_of<'a>(name: &str, commands: &'a [Vec<String>]) -> &'a [String] {
    commands
        .iter()
        .find(|path| op_name(path) == Some(name))
        .unwrap_or_else(|| panic!("{name}: no command runs it"))
}

/// A command's page, from `docs/reference/mcp-tools/`: `["op", "log"]` → `../commands/op-log.md`.
fn command_link(path: &[String]) -> String {
    format!("../commands/{}.md", path.join("-"))
}

// ---- The golden steps ----

/// One exchange of an MCP transcript: what the client sent and, for a request, the reply.
struct Exchange {
    request: Value,
    response: Option<Value>,
}

/// The golden MCP transcripts the pages show.
struct Golden {
    /// The command line of the server the tool calls ran on.
    args: String,
    calls: Vec<Exchange>,
    session: Vec<Exchange>,
}

impl Golden {
    /// Both transcripts, read once.
    fn read() -> Self {
        let (args, calls) = transcript(TOOL_CALLS);
        let (_, session) = transcript(SESSION);
        Self {
            args,
            calls,
            session,
        }
    }

    /// The first `tools/call` of tool `name`.
    fn call_of(&self, name: &str) -> Option<&Exchange> {
        self.calls.iter().find(|step| {
            step.request["method"] == TOOLS_CALL && step.request["params"]["name"] == name
        })
    }

    /// The session's `initialize` exchange.
    fn initialize(&self) -> &Exchange {
        self.session
            .iter()
            .find(|step| step.request["method"] == INITIALIZE)
            .unwrap_or_else(|| panic!("{SESSION}: no {INITIALIZE}"))
    }
}

/// Transcript `name`: its server's command line and its exchanges.
fn transcript(name: &str) -> (String, Vec<Exchange>) {
    let path = format!("{}/{SNAPSHOTS}/{name}", env!("CARGO_MANIFEST_DIR"));
    let text = fs::read_to_string(&path).unwrap_or_else(|e| panic!("{SNAPSHOTS}/{name}: {e}"));

    // 1. The value after insta's header.
    let body = text
        .strip_prefix("---\n")
        .and_then(|rest| rest.split_once("\n---\n"))
        .map_or_else(
            || panic!("{SNAPSHOTS}/{name}: no insta header"),
            |(_, body)| body,
        );
    let value: Value =
        serde_json::from_str(body).unwrap_or_else(|e| panic!("{SNAPSHOTS}/{name}: {e}"));

    // 2. `{"args": …, "steps": [{"request", "response"?}…]}`.
    let args = value["args"].as_str().unwrap_or_default().to_owned();
    let steps = value["steps"]
        .as_array()
        .unwrap_or_else(|| panic!("{SNAPSHOTS}/{name}: no steps"))
        .iter()
        .map(|step| Exchange {
            request: step["request"].clone(),
            response: step.get("response").cloned(),
        })
        .collect();
    (args, steps)
}

/// `value` as the pages show JSON: indented by two spaces.
fn pretty(value: &Value) -> String {
    serde_json::to_string_pretty(value).expect("a JSON value serializes")
}

/// An exchange as two `json` fences: the request, then the reply when there is one.
fn exchange(out: &mut String, step: &Exchange) {
    let _ = writeln!(out, "```json\n{}\n```\n", pretty(&step.request));
    if let Some(response) = &step.response {
        let _ = writeln!(out, "```json\n{}\n```\n", pretty(response));
    }
}

// ---- The index ----

/// Renders the index.
fn index(golden: &Golden, commands: &[Vec<String>]) -> String {
    let mut out = String::new();

    // 1. Title and what the pages are.
    let _ = writeln!(out, "{GENERATED}\n");
    let _ = writeln!(out, "# MCP tools\n");
    let _ = writeln!(
        out,
        "`{BIN} mcp` serves the store's operations as an MCP server on stdin and stdout: \
         JSON-RPC 2.0, one message per line. Each tool is one operation, named as the \
         envelope's `op` is, and its result holds the envelope the CLI prints for the same \
         request. These pages are generated from the server's own tool table, so they say what \
         `tools/list` says. [MCP integration](../../develop/mcp.md) shows how to register the \
         server and use it.\n"
    );

    // 2. The tools.
    tools_table(&mut out, commands);

    // 3. The protocol.
    versions(&mut out);
    instructions(&mut out, golden);
    identity(&mut out);
    limits(&mut out);
    rpc_errors(&mut out);

    // 4. Where to go next.
    let _ = writeln!(out, "## See also\n");
    let _ = writeln!(out, "- [MCP integration](../../develop/mcp.md)");
    let _ = writeln!(out, "- [`{BIN} mcp`](../commands/mcp.md)");
    let _ = writeln!(out, "- [CLI reference](../cli.md)");
    let _ = writeln!(out, "- [Error codes](../errors.md)");
    trim_end(out)
}

/// The table of tools, and the commands that have none.
fn tools_table(out: &mut String, commands: &[Vec<String>]) {
    let _ = writeln!(out, "## Tools\n");
    let _ = writeln!(out, "In `tools/list`'s order.\n");

    // 1. One row per tool.
    let _ = writeln!(
        out,
        "| Tool | Title | CLI command | Changes the store | Needs an identity |"
    );
    let _ = writeln!(out, "| --- | --- | --- | --- | --- |");
    for spec in &TOOLS {
        let command = command_of(spec.name, commands);
        let _ = writeln!(
            out,
            "| [`{0}`]({1}) | {2} | [`{BIN} {3}`]({4}) | {5} | {6} |",
            spec.name,
            file_name(spec.name),
            spec.title,
            command.join(" "),
            command_link(command),
            changes(spec.effect),
            yes_no(needs_identity(spec.effect))
        );
    }
    out.push('\n');

    // 2. The commands no tool runs.
    let without: Vec<String> = commands
        .iter()
        .filter(|path| {
            let op = op_name(path).unwrap_or_default();
            let stored = TOOLS.iter().any(|spec| spec.name == op);
            let in_workspace = WS_TOOLS.iter().any(|spec| spec.name == op);
            !stored && !in_workspace
        })
        .map(|path| format!("[`{BIN} {}`]({})", path.join(" "), command_link(path)))
        .collect();
    let _ = writeln!(
        out,
        "These commands have no tool: {}. An operator or a script runs them as commands; \
         `derive` runs beside the store as maintenance, deriving values ahead of readers.\n",
        without.join(", ")
    );
}

/// What a tool of `effect` does to the store, in a few words.
fn changes(effect: Effect) -> &'static str {
    match effect {
        Effect::Reads => "no",
        Effect::Adds => "adds to it",
        Effect::Moves => "moves refs",
        Effect::Lands => "adds a changeset and moves the target",
        Effect::Fetches => "adds what a git remote holds, or sends it there",
        Effect::Syncs => "lands onto a git remote's head, moves main and pushes",
    }
}

/// Whether a tool of `effect` needs the server's identity: every tool but those that only read,
/// and `fetch` and `push`, which move no ref of the store and record no agent.
fn needs_identity(effect: Effect) -> bool {
    !matches!(effect, Effect::Reads | Effect::Fetches)
}

/// The protocol revisions, and how a client opens each.
fn versions(out: &mut String) {
    let _ = writeln!(out, "## Protocol versions\n");
    let _ = writeln!(out, "| Version | How a client opens it |");
    let _ = writeln!(out, "| --- | --- |");

    // 1. Each revision the server serves, newest first.
    for version in SUPPORTED {
        let how = if version == LATEST {
            format!(
                "No handshake: each request names it in `params._meta` under `{VERSION_KEY}`, \
                 with the client's capabilities under `{CAPABILITIES_KEY}`."
            )
        } else if version == PREVIOUS {
            "`initialize`; also the version a client gets when it asks for one the handshake \
             does not serve."
                .to_owned()
        } else {
            "`initialize`.".to_owned()
        };
        let _ = writeln!(out, "| {version} | {how} |");
    }
    out.push('\n');

    // 2. What differs between them.
    let earliest = HANDSHAKE[HANDSHAKE.len() - 1];
    let _ = writeln!(
        out,
        "The handshake revisions get the same tools and results. Revisions older than \
         {earliest} are not served. In {LATEST}, a result has `resultType: \"complete\"` and the server's identity \
         in `_meta`, and the results of `server/discover` and `tools/list` say a client may keep \
         them for `ttlMs` {TTL_MS} (an hour) with `cacheScope: \"public\"`: they change only with \
         the binary. [MCP integration: Protocol versions](../../develop/mcp.md#protocol-versions) \
         shows a session of each.\n"
    );
}

/// The server's instructions, and a recorded `initialize`.
fn instructions(out: &mut String, golden: &Golden) {
    let _ = writeln!(out, "## Server instructions\n");
    let _ = writeln!(
        out,
        "`initialize` and `server/discover` return this text as `instructions`, for the client's \
         model: {} characters on one line.\n",
        INSTRUCTIONS.chars().count()
    );
    let _ = writeln!(out, "```text\n{INSTRUCTIONS}\n```\n");

    // A recorded handshake.
    let _ = writeln!(out, "### Example: initialize\n");
    exchange(out, golden.initialize());
    let _ = writeln!(out, "{PLACEHOLDERS}\n");
}

/// Where the store and the identity come from.
fn identity(out: &mut String) {
    let readers: Vec<String> = TOOLS
        .iter()
        .filter(|spec| !needs_identity(spec.effect))
        .map(|spec| format!("`{}`", spec.name))
        .collect();
    let writers: Vec<String> = TOOLS
        .iter()
        .filter(|spec| needs_identity(spec.effect))
        .map(|spec| format!("`{}`", spec.name))
        .collect();

    let _ = writeln!(out, "## The store and the identity\n");
    let _ = writeln!(
        out,
        "Both are the server's, never a call's; no tool argument names either.\n"
    );
    let _ = writeln!(
        out,
        "- The store is `--repo`, else `SWARMOPS_REPO`, opened anew for each call, so that a call \
         sees what other processes committed. A store that is not there is each call's \
         `E_NOT_A_REPO`, and the server serves on."
    );
    let _ = writeln!(
        out,
        "- The identity is `--as`, else `SWARMOPS_AGENT`, with `SWARMOPS_RUN_ID`, as for the CLI. \
         Every change is recorded for it."
    );
    let _ = writeln!(
        out,
        "- These tools need it, and without one fail with `E_IDENTITY_REQUIRED`: {}.",
        writers.join(", ")
    );
    let _ = writeln!(out, "- These need none: {}.", readers.join(", "));
    let _ = writeln!(
        out,
        "- The output flags (`--json`, `--human`, `--pretty`) do not apply.\n"
    );
}

/// The limits on what goes in and what comes out.
fn limits(out: &mut String) {
    let _ = writeln!(out, "## Result size limits\n");

    // 1. What the tools ask of a client.
    let raised: Vec<String> = TOOLS
        .iter()
        .filter_map(|spec| {
            let chars = spec.result_chars?;
            Some(format!(
                "`{}` carries `_meta: {{\"{RESULT_CHARS_KEY}\": {chars}}}`",
                spec.name
            ))
        })
        .collect();
    let _ = writeln!(
        out,
        "A result holds its envelope twice, so the descriptions of the tools that read much ask \
         the model for small reads and pages. In `tools/list`, {}: Claude Code keeps a result of up to that many \
         characters in the conversation instead of saving it to a file. The other tools carry \
         no `_meta`. [MCP integration: Result size limits](../../develop/mcp.md#result-size-limits) \
         gives the sizes each tool asks for.\n",
        raised.join("; ")
    );

    // 2. What a message may hold.
    let _ = writeln!(
        out,
        "A message line longer than {} MiB is an Invalid Request (`{INVALID_REQUEST}`) without \
         an `id`, read no further than one byte past the limit.\n",
        MAX_REQUEST_BYTES >> 20
    );
}

