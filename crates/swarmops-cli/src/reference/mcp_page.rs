//! The MCP tool pages: `docs/reference/mcp-tools/README.md`, the index, and one page per tool,
//! `docs/reference/mcp-tools/<tool>.md`, its name the tool's with `-` for `_` (`read_file` →
//! `read-file.md`). A child of `mcp`, since the tool table and the server's constants are private
//! there.
//!
//! A tool page is, in order: the generated marker; the title and the tool's description; the
//! metadata, a `yaml` block (title, description, since, mutates, identity_required,
//! cli_command, envelope_op, request_type, annotations, max_result_chars); Input schema;
//! Annotations; Examples, the tool's `tools/call` step of the golden MCP snapshots; Details, the
//! hand-written note; Return information; Errors; See also.
//!
//! Where each part comes from:
//!
//! ```text
//! TOOLS (name, title, description, effect) ─ title, description, mutates, annotations
//! tool_input_schema ─────────────────────── Input schema
//! the clap grammar and op_name ──────────── the CLI command
//! tests/snapshots/all__mcp__*_golden.snap ─ Examples
//! notes/mcp-tools/<tool>.md ─────────────── Details
//! LATEST, HANDSHAKE, INSTRUCTIONS, … ────── the index
//! ```
//!
//! `mcp_tool_pages_match` fails when a committed page is not its rendering;
//! `SWARMOPS_REGEN_REFERENCE=1` with the ignored `regen_reference_mcp_tools` writes them again,
//! and the command that regenerates the other reference pages runs it too (its filter,
//! `test(regen_reference)`, matches both).

