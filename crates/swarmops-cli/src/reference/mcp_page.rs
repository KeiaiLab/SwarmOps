/// The first line where `want` and `got` differ, numbered from 1, with both versions.
fn first_difference(want: &str, got: &str) -> String {
    let mut want_lines = want.lines();
    let mut got_lines = got.lines();
    for number in 1.. {
        let (w, g) = (want_lines.next(), got_lines.next());
        if w.is_none() && g.is_none() {
            break;
        }
        if w != g {
            return format!(
                "line {number}:\n  generated: {}\n  committed: {}",
                w.unwrap_or("<end>"),
                g.unwrap_or("<end>")
            );
        }
    }
    "only line endings differ".to_owned()
}

/// The files in `docs/reference/<dir>/` that `names` does not hold, by their path in
/// `docs/reference/`.
fn strays(dir: &str, names: &[String]) -> Vec<String> {
    let Ok(entries) = fs::read_dir(reference_dir().join(dir)) else {
        return Vec::new();
    };
    let mut stray: Vec<String> = entries
        .map(|entry| entry.expect("a directory entry"))
        .map(|entry| format!("{dir}/{}", entry.file_name().to_string_lossy()))
        .filter(|name| !names.contains(name))
        .collect();
    stray.sort();
    stray
}

/// Each committed page is what the code renders, no other page is in `docs/reference/mcp-tools/`,
/// and every note is a tool's.
#[test]
fn mcp_tool_pages_match() {
    let dir = reference_dir();
    let pages = pages();

    // 1. No page cites a design document's section.
    for page in &pages {
        assert!(
            !page.text.contains('\u{a7}'),
            "docs/reference/{} cites a section",
            page.name
        );
    }

    // 2. Each page, as rendered.
    for page in &pages {
        let committed = fs::read_to_string(dir.join(&page.name)).unwrap_or_default();
        assert!(
            committed == page.text,
            "docs/reference/{} is not what the code renders; run `{REGEN_CMD}`, review the diff \
             and commit it. First difference, {}",
            page.name,
            first_difference(&page.text, &committed)
        );
    }

    // 3. Nothing else among the pages.
    let names: Vec<String> = pages.iter().map(|page| page.name.clone()).collect();
    let stale = strays(DIR, &names);
    assert!(
        stale.is_empty(),
        "docs/reference/{stale:?}: no tool renders these; run `{REGEN_CMD}`"
    );

    // 4. A note names a tool.
    let notes: Vec<String> = TOOLS
        .iter()
        .map(|spec| format!("{NOTES_DIR}/{}", file_name(spec.name)))
        .collect();
    let orphans = strays(NOTES_DIR, &notes);
    assert!(
        orphans.is_empty(),
        "docs/reference/{orphans:?}: no such tool"
    );
}

/// Writes the pages again. Writes nothing unless `SWARMOPS_REGEN_REFERENCE=1` is set, so that
/// `--run-ignored all` never rewrites them.
#[test]
#[ignore = "writes docs/reference/mcp-tools when SWARMOPS_REGEN_REFERENCE=1; run on purpose"]
fn regen_reference_mcp_tools() {
    if std::env::var_os(REGEN_VAR).is_none() {
        eprintln!("regen_reference_mcp_tools: {REGEN_VAR} not set; nothing written");
        return;
    }
    let dir = reference_dir();
    let pages = pages();

    // 1. The pages no tool renders any more go.
    let names: Vec<String> = pages.iter().map(|page| page.name.clone()).collect();
    for name in strays(DIR, &names) {
        fs::remove_file(dir.join(name)).unwrap();
    }

    // 2. Every page, written again.
    for page in pages {
        let path = dir.join(&page.name);
        fs::create_dir_all(path.parent().unwrap()).unwrap();
        fs::write(path, page.text).unwrap();
    }
}

