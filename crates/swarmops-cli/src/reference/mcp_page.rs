/// `text` as a double-quoted YAML scalar, which a JSON string is.
fn quoted(text: &str) -> String {
    Value::from(text).to_string()
}

/// Text that ends as a sentence does.
fn sentence(text: &str) -> String {
    let text = text.trim_end();
    if text.is_empty() || text.ends_with('.') {
        return text.to_owned();
    }
    format!("{text}.")
}

/// `yes` or `no`.
fn yes_no(value: bool) -> &'static str {
    if value { "yes" } else { "no" }
}

/// Escapes text for Markdown outside code spans, so that `<name>` stays text rather than HTML
/// and `main~1` no strikethrough; inside a table cell, `|` too.
fn escape(text: &str) -> String {
    let mut out = String::new();
    for (i, part) in text.split('`').enumerate() {
        if i > 0 {
            out.push('`');
        }

        // Odd parts are code spans: only a table's `|` needs escaping there.
        if i % 2 == 1 {
            out.push_str(&cell_code(part));
            continue;
        }
        for c in part.chars() {
            match c {
                '<' => out.push_str("&lt;"),
                '>' => out.push_str("&gt;"),
                '\\' | '|' | '*' | '_' | '~' | '[' | ']' => {
                    out.push('\\');
                    out.push(c);
                }
                _ => out.push(c),
            }
        }
    }
    out
}

/// Code span text inside a table cell: its `|` escaped.
fn cell_code(text: &str) -> String {
    text.replace('|', "\\|")
}

/// Text as one table cell: its lines joined, escaped.
fn cell(text: &str) -> String {
    escape(&text.split_whitespace().collect::<Vec<_>>().join(" "))
}

/// The page with exactly one newline at its end.
fn trim_end(mut text: String) -> String {
    let kept = text.trim_end().len();
    text.truncate(kept);
    text.push('\n');
    text
}

